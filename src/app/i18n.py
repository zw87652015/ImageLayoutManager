def tr(key: str) -> str:
    """Return the translation for *key* in the current language, falling back to English."""
    return _T.get(key, {}).get(_lang) or _T.get(key, {}).get("en") or key


def set_language(lang: str) -> None:
    global _lang
    if lang in ("en", "zh"):
        _lang = lang


def current_language() -> str:
    return _lang
